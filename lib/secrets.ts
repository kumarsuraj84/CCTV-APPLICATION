import { randomBytes } from 'node:crypto'
import { processSingleton } from '@/lib/process-singleton'

// One secret per purpose. A missing one means "not available" (the feature is off and says so), never "use another secret".
// access_preview (P2-3 review M-5): the key of the access editor's preview token (an HMAC binding a save to the preview shown).
// P2-6 (brief item 7, addendum): merge_confirm (the merge-confirmation HMAC of P2-5c), verified_user (the proxy's verified-user header,
// which used to be signed with the service key), go2rtc_api (go2rtc's API password, D-13), and the purposes of later packages: signer
// (D-9 command signing), agent_ingest (endpoint agent check-ins), audit_checkpoint (D-15 audit checkpoints). Every one is generated by
// `node scripts/gen-secrets.mjs` and rotated as docs/drishti/runbooks/secret-rotation.md says.
export type SecretPurpose =
  | 'cron' | 'worker' | 'stream_token' | 'system_log_ingest' | 'access_preview'
  | 'merge_confirm' | 'verified_user' | 'go2rtc_api' | 'signer' | 'agent_ingest' | 'audit_checkpoint'

type Spec = { env: string; min: number; required: boolean }
/** `required`: reported as "not set" by auditSecrets when missing (the five of the first release); the others only when set but unusable. */
const SPEC: Record<SecretPurpose, Spec> = {
  cron: { env: 'CRON_SECRET', min: 16, required: true },
  worker: { env: 'WORKER_SECRET', min: 16, required: true },
  stream_token: { env: 'STREAM_TOKEN_SECRET', min: 16, required: true },
  system_log_ingest: { env: 'SYSTEM_LOG_INGEST_SECRET', min: 16, required: true },
  access_preview: { env: 'ACCESS_PREVIEW_SECRET', min: 16, required: true },
  merge_confirm: { env: 'MERGE_CONFIRM_SECRET', min: 32, required: false },
  verified_user: { env: 'VERIFIED_USER_SECRET', min: 32, required: false },
  go2rtc_api: { env: 'GO2RTC_API_PASSWORD', min: 32, required: false },
  signer: { env: 'SIGNER_SECRET', min: 32, required: false },
  agent_ingest: { env: 'AGENT_INGEST_SECRET', min: 32, required: false },
  audit_checkpoint: { env: 'AUDIT_CHECKPOINT_SECRET', min: 32, required: false },
}

/** The smallest length any purpose accepts (the first five; the P2-6 purposes need 32). */
export const MIN_SECRET_LENGTH = 16
const clean = (v: string | undefined) => (typeof v === 'string' && v.trim() !== '' ? v : null)

/** A secret value that may be used: not blank and at least `min` characters. Anything else counts as "not set". */
export const usableSecret = (v: string | null | undefined, min: number = MIN_SECRET_LENGTH): string | null => {
  const c = clean(v ?? undefined)
  return c !== null && c.length >= min ? c : null
}

/** The secret for this purpose, or null when it is not configured (or too short to be safe). The caller must then refuse or switch the feature off. */
export function getSecret(purpose: SecretPurpose, env: Record<string, string | undefined> = process.env): string | null {
  const s = SPEC[purpose]
  return usableSecret(env[s.env], s.min)
}

export const secretEnvName = (purpose: SecretPurpose) => SPEC[purpose].env
export const secretMinLength = (purpose: SecretPurpose) => SPEC[purpose].min

const processKeys = processSingleton('secrets.processKeys', () => new Map<SecretPurpose, string>())

/**
 * A secret that every app instance must share (P2-6 addendum: the merge confirmation, the access preview): the configured one when it is
 * set, so a confirmation made by one instance is accepted by another. Without it, outside production, one random key for this process
 * (one instance only; after a restart the person simply confirms again); in production null (the feature refuses until it is set).
 */
export function sharedSecret(purpose: SecretPurpose, env: Record<string, string | undefined> = process.env): string | null {
  const configured = getSecret(purpose, env)
  if (configured) return configured
  if (env.NODE_ENV === 'production') return null
  let k = processKeys.get(purpose)
  if (!k) {
    k = randomBytes(32).toString('base64url')
    processKeys.set(purpose, k)
  }
  return k
}

export type SecretIssue = { purpose: SecretPurpose; env: string; problem: string }

/** What is wrong with the configured secrets, without ever returning a value. */
export function auditSecrets(env: Record<string, string | undefined> = process.env): SecretIssue[] {
  const issues: SecretIssue[] = []
  const seen = new Map<string, string>()
  for (const purpose of Object.keys(SPEC) as SecretPurpose[]) {
    const { env: name, min, required } = SPEC[purpose]
    const v = clean(env[name])
    if (!v) {
      if (required) issues.push({ purpose, env: name, problem: 'not set' })
      continue
    }
    if (v.length < min) issues.push({ purpose, env: name, problem: `shorter than ${min} characters` })
    const other = seen.get(v)
    if (other) issues.push({ purpose, env: name, problem: `the same value as ${other}` })
    else seen.set(v, name)
  }
  return issues
}
